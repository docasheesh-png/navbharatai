// A DARK-MODE MAPPING DOES WHAT ITS TABLE SAYS (2026-10-11, Q-789).
//
// The Dark Mode Generator showed a "Color Mappings" table with an Override picker for every strategy, but only
// "Manual Override" read it — in CSS Variables (the recommended one), Class Toggle and color-scheme an override
// changed nothing. And Manual set `color` AND `background-color` to the same value, painting text invisible on
// its own background. THE CLASS: a control whose value the output never reads. These tests pin the fix, and that
// a strategy WITHOUT overrides emits exactly what it emitted before (nobody's saved dark mode changes).
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { buildDarkCSS, propertyForUsage, type ColorMapping, type DarkStrategy, type DarkTheme } from '../src/lib/darkModeCss';

const theme: DarkTheme = { bg: '#0d1117', bgSecondary: '#161b22', text: '#e6edf3', textSecondary: '#8b949e', accent: '#58a6ff', border: 'rgba(255,255,255,0.1)' };
const mappings: ColorMapping[] = [
  { original: '#ffffff', dark: '#0d1117', usage: 'Background' },
  { original: '#333333', dark: '#e6edf3', usage: 'Text' },
  { original: '#dddddd', dark: '#30363d', usage: 'Neutral' },
  { original: '#ff6600', dark: '#ff8a3d', usage: 'Accent' },
];

/** The builder as it was before Q-789, for the three strategies that must not change without overrides. */
function legacy(ms: ColorMapping[], strategy: Exclude<DarkStrategy, 'manual'>, t: DarkTheme): string {
  const vars = `  --bg-primary: ${t.bg};\n  --bg-secondary: ${t.bgSecondary};\n  --text-primary: ${t.text};\n  --text-secondary: ${t.textSecondary};\n  --accent: ${t.accent};\n  --border: ${t.border};`;
  if (strategy === 'css-vars') {
    return `/* Dark Mode — Auto-generated by NavBharatAI */\n@media (prefers-color-scheme: dark) {\n  :root {\n${vars}\n  }\n  body {\n    background: var(--bg-primary);\n    color: var(--text-primary);\n  }\n  a { color: var(--accent); }\n  input, textarea, select {\n    background: var(--bg-secondary);\n    color: var(--text-primary);\n    border-color: var(--border);\n  }\n  button {\n    background: var(--bg-secondary);\n    color: var(--text-primary);\n    border: 1px solid var(--border);\n  }\n${ms.map(m => `  /* ${m.usage}: ${m.original} */`).join('\n')}\n}`;
  }
  if (strategy === 'class-toggle') {
    return `/* Dark Mode (class toggle) — Auto-generated by NavBharatAI */\nhtml.dark {\n  --bg-primary: ${t.bg};\n  --bg-secondary: ${t.bgSecondary};\n  --text-primary: ${t.text};\n  --text-secondary: ${t.textSecondary};\n  --accent: ${t.accent};\n  --border: ${t.border};\n}\nhtml.dark body {\n  background: var(--bg-primary);\n  color: var(--text-primary);\n}\nhtml.dark a { color: var(--accent); }\nhtml.dark input, html.dark textarea, html.dark select {\n  background: var(--bg-secondary);\n  color: var(--text-primary);\n  border-color: var(--border);\n}`;
  }
  return `/* Dark Mode (color-scheme) — Auto-generated by NavBharatAI */\n:root { color-scheme: light dark; }\n@media (prefers-color-scheme: dark) {\n  body { background: ${t.bg}; color: ${t.text}; }\n}`;
}

/** Every swap rule as [selector, property, value]. */
const rules = (css: string) => [...css.matchAll(/((?:html\.dark )?\[style\*="#[0-9a-f]+"\]) \{ ([a-z-]+): ([^ ;]+) !important; \}/g)].map((m) => [m[1], m[2], m[3]]);

describe('a colour is swapped only on the property it was found on', () => {
  it('Background → background-color, Text and Accent → color, Neutral → border-color', () => {
    expect(propertyForUsage('Background')).toBe('background-color');
    expect(propertyForUsage('Text')).toBe('color');
    expect(propertyForUsage('Accent')).toBe('color');
    expect(propertyForUsage('Neutral')).toBe('border-color');
  });

  it('🔒 Manual never sets text and background to one value (the invisible-text bug)', () => {
    const css = buildDarkCSS(mappings, 'manual', theme);
    expect(css).not.toMatch(/color: [^;]+ !important; background-color:/);
    expect(rules(css)).toEqual([
      ['[style*="#ffffff"]', 'background-color', '#0d1117'],
      ['[style*="#333333"]', 'color', '#e6edf3'],
      ['[style*="#dddddd"]', 'border-color', '#30363d'],
      ['[style*="#ff6600"]', 'color', '#ff8a3d'],
    ]);
  });
});

describe('an override does something in every strategy', () => {
  const overridden = mappings.map((m, i) => (i === 0 ? { ...m, override: '#101010' } : m));

  it('🔒 CSS Variables, Class Toggle and color-scheme each carry the override as a real rule in their dark scope', () => {
    expect(rules(buildDarkCSS(overridden, 'css-vars', theme))).toEqual([['[style*="#ffffff"]', 'background-color', '#101010']]);
    expect(rules(buildDarkCSS(overridden, 'class-toggle', theme))).toEqual([['html.dark [style*="#ffffff"]', 'background-color', '#101010']]);
    expect(rules(buildDarkCSS(overridden, 'color-scheme', theme))).toEqual([['[style*="#ffffff"]', 'background-color', '#101010']]);
    // the media-query strategies keep it INSIDE the dark block
    for (const s of ['css-vars', 'color-scheme'] as const) {
      const css = buildDarkCSS(overridden, s, theme);
      expect(css.indexOf('[style*="#ffffff"]')).toBeLessThan(css.lastIndexOf('}'));
      expect(css.indexOf('@media (prefers-color-scheme: dark)')).toBeLessThan(css.indexOf('[style*="#ffffff"]'));
    }
  });

  it('Manual uses the override instead of the mapped colour', () => {
    expect(rules(buildDarkCSS(overridden, 'manual', theme))[0]).toEqual(['[style*="#ffffff"]', 'background-color', '#101010']);
  });
});

describe('nobody\'s dark mode changes unless they override', () => {
  it('🔒 without overrides, the three non-manual strategies emit byte-for-byte what they did before', () => {
    for (const s of ['css-vars', 'class-toggle', 'color-scheme'] as const) {
      expect(buildDarkCSS(mappings, s, theme)).toBe(legacy(mappings, s, theme));
    }
  });

  it('the component builds through this module — no second copy of the builder', () => {
    const src = readFileSync('src/components/ide/DarkModeGenerator.tsx', 'utf8');
    expect(src).toMatch(/from '\.\.\/\.\.\/lib\/darkModeCss'/);
    expect(src).not.toMatch(/function buildDarkCSS\(/);
  });
});
