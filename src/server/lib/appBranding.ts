// APP BRANDING FOR THE MOBILE SHIP (admin 2026-10-16: "APP LOGO AND NATIVE APP ICON MUST BOTH BE CUSTOM";
// admin 2026-10-21: "pehle lucide, fir alfabet; AI se logo nahi banwana, user khud banwa lega").
//
// THE CLASS. A native app that carries somebody else's picture on the user's home screen: Capacitor's default icon
// (no logo uploaded, or the icon generator failed with only a warning), another app's icon left in a reused native
// project, or the platform's own. Nothing used to look at what was inside the native project, so every one of those
// shipped silently.
//
// THE RULE, in priority order:
//   1. the logo the owner chose (uploaded, or made by them in AI Image Gen) — always wins;
//   2. otherwise the app's own MARK (src/lib/brandMark.ts): a Lucide symbol that fits its name, else the first letter of
//      its name, else a stable symbol picked by the name. Nothing is generated by AI and nothing is bought.
//   Never Capacitor's icon, never the platform's, never a stale one.
//
// THE DESIGN. Three layers, each doing one job:
//   1. HERE (server, before the push): decide which logo the app has and write the files the next layers need — the branding
//      script, `resources/branding.json`, the ready-drawn mark as SVG, and (when chosen) the owner's logo.
//   2. THE SCRIPT (scripts/nbai-branding.mjs, run on the GitHub runner): validate the logo, draw the mark to a PNG, generate
//      the launcher icons / splash / PWA icons, and verify the NATIVE project. It never finishes while the project still
//      holds a default or stale icon.
//   3. THE WORKFLOWS (mobileShipKit.ts): call the script before Gradle / Xcode, so the artifact is built from the verified project.
//
// PURE.
import { BRANDING_SCRIPT, BRANDING_SCRIPT_PATH } from './appBrandingScript';
import { chooseMark, markLabel, markSvg, type BrandMark } from '../../lib/brandMark';

export const BRANDING_JSON_PATH = 'resources/branding.json';
export const BRAND_MARK_PATH = 'resources/brand-mark.svg';
export const BRAND_MARK_FG_PATH = 'resources/brand-mark-fg.svg';

export type DeclaredLogo = 'user' | 'none';

export interface LogoDecision {
  declared: DeclaredLogo;
  /** The owner's logo as a data URL when `declared` is 'user'. */
  dataUrl?: string;
}

const IMAGE_DATA_URL = /^data:image\/(png|jpe?g|webp);base64,[A-Za-z0-9+/=\s]+$/i;

/** Which logo does this app have? The owner's explicit choice always wins; with none, the app's own mark is used. */
export function decideLogo(opts: { iconDataUrl?: string }): LogoDecision {
  if (opts.iconDataUrl && IMAGE_DATA_URL.test(opts.iconDataUrl.trim())) return { declared: 'user', dataUrl: opts.iconDataUrl.trim() };
  return { declared: 'none' };
}

/** The seed that keys the fallback blocks mark: same app → same look; two apps → two looks. */
export function brandingSeed(appId: string, appName: string): string {
  return `${appId}|${appName}`;
}

/** The files the branding step needs in the project. The owner's logo bytes are written by the assembler beside them. */
export function brandingTextFiles(opts: { appName: string; appId: string; decision: LogoDecision; /** The exact file the logo was written to ('' when there is none). */ iconFile?: string }): Record<string, string> {
  const mark = chooseMark(opts.appName);
  const json = {
    appName: opts.appName,
    appId: opts.appId,
    declared: opts.decision.declared,
    iconFile: opts.iconFile || '',
    seed: brandingSeed(opts.appId, opts.appName),
    mark: markLabel(mark),
  };
  return {
    [BRANDING_SCRIPT_PATH]: BRANDING_SCRIPT,
    [BRANDING_JSON_PATH]: JSON.stringify(json, null, 2) + '\n',
    // The mark, already drawn: the runner only has to turn these into PNGs. Written even when the owner chose a logo (the
    // script ignores them then), so a logo that turns out to be unusable falls back to the mark, not to nothing.
    [BRAND_MARK_PATH]: markSvg(mark, { size: 1024, tile: 'square' }),
    [BRAND_MARK_FG_PATH]: markSvg(mark, { size: 1024, tile: 'none' }),
  };
}

/** One sentence for the ship notes, so the owner is never left guessing which icon their app got. PURE. */
export function brandingNote(decision: LogoDecision, mark: BrandMark | string): string {
  const label = typeof mark === 'string' ? mark : markLabel(mark);
  if (decision.declared === 'user') return 'Your logo is used for the app icon, the splash screen and the web install icon.';
  const what = label.startsWith('letter:') ? `the letter ${label.slice(7)}` : 'a symbol that fits its name';
  return `No logo was chosen, so your app got its own mark — ${what} on its own colour — for the app icon, the splash screen and the web install icon. Choose or upload a logo in the APK builder to replace it.`;
}
