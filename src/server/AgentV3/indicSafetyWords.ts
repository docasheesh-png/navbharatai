/** Malayalam chillu letters and the two-character spelling each also has. */
const CHILLU: Readonly<Record<string, string>> = {
  'ൺ': 'ണ്', 'ൻ': 'ന്', 'ർ': 'ര്', 'ൽ': 'ല്', 'ൾ': 'ള്',
};
/** Urdu letters and the Arabic-keyboard code point a user may type for the same letter. */
const ARABIC_TWIN: Readonly<Record<string, string>> = { 'ی': 'يى', 'ک': 'ك', 'ہ': 'ه' };

/** One word as a regex fragment, matching the forms `normalizeScanText` leaves in the input. Pure. */
export function indicWordPattern(word: string): string {
  const nfc = word.normalize('NFC').replace(/[​-‍⁠﻿]/g, '');
  let out = '';
  for (const ch of nfc) {
    if (CHILLU[ch]) out += `(?:${ch}|${CHILLU[ch]})`;
    else if (ARABIC_TWIN[ch]) out += `[${ch}${ARABIC_TWIN[ch]}]`;
    else out += ch;
  }
  return out;
}

/** Every script's words for one field, as regex alternatives. Pure. */
export function indicAlternatives(words: ScriptWords): string[] {
  return INDIC_SCRIPTS.flatMap((s) => words[s].map(indicWordPattern));
}
