const join = (...lists: ScriptWords[]): ScriptWords =>
  Object.fromEntries(INDIC_SCRIPTS.map((s) => [s, lists.flatMap((l) => l[s])])) as unknown as ScriptWords;
const after = (head: ScriptWords, tail: ScriptWords): ScriptWords =>
  Object.fromEntries(INDIC_SCRIPTS.map((s) => [s, head[s].map((h) => `${h}\\s*(?:${tail[s].join('|')})`)])) as unknown as ScriptWords;

