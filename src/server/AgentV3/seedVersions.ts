//
// 🔴 WHAT HAPPENED. A user typed "Banao" into a workspace holding nothing but our persisted starter, and the engine
// built a made-up todo app for ₹96.93 instead of asking what to build. The guard that asks existed; it was fed
// "is any file here?" instead of "is anything here somebody's work?". Answering the right question needs a
// definition of "ours", and every definition in the engine was "byte-equal to TODAY's template".
//
// 🔑 THE CLASS: "ours" pinned to the current version of a template. The design kit changes every few weeks, and
// each change silently turned every workspace still holding the PREVIOUS starter into "the user's app": the
// request edits instead of builds, our starter is graded as their code, "Banao" is built instead of asked about.
// The game kit had the same class (Q-863) and was fixed for the game kit alone; this is the starter's half.
//
// `platformSeedHistory.ts` (generated by `node scripts/platformSeedHistory.mjs`) holds the hash of every version
// every framework starter and every starter-chip template has written. A file that hashes to one of them is our
// untouched work; one changed byte makes it the user's, exactly as before.
//
// ⚠️ NORMALISED, NOT BYTE-EXACT: line endings and leading/trailing whitespace are ignored, the way
// `starterFragment.sameFile` has always compared starters. Neither can carry code, so no edit is forgiven.
//
// PURE. Never throws.

import { createHash } from 'node:crypto';
import { PLATFORM_SEED_HISTORY } from './platformSeedHistory';
import { withoutPreviewBridge } from './previewBridge';

/**
 * Which templates count. `starter` = the framework starter every sandbox is seeded with (what "replace the
 * starter" and "never restore the starter's manifest over a project" mean); `any` = that plus every starter
 * chip's tested template (what "nothing here is anybody's work" means).
 */
export type SeedSource = 'starter' | 'any';

/** The history's key for a file's content — must match `seedHash` in scripts/platformSeedHistory.mjs. */
export function seedHash(content: string): string {
  return createHash('sha256').update(String(content).replace(/\r\n/g, '\n').trim(), 'utf8').digest('hex').slice(0, 24);
}

function historyKey(path: string): string {
  return path.replace(/\\/g, '/').replace(/^\.?\/+/, '').trim();
}

/** Is this file, untouched, a version of `path` that one of our templates has ever written? PURE. */
export function isKnownSeedVersion(path: string | null | undefined, content: string | null | undefined, source: SeedSource = 'any'): boolean {
  if (typeof path !== 'string' || typeof content !== 'string' || !content.trim()) return false;
  try {
    const key = historyKey(path);
    const lists = source === 'starter'
      ? [PLATFORM_SEED_HISTORY.starter[key]]
      : [PLATFORM_SEED_HISTORY.starter[key], PLATFORM_SEED_HISTORY.golden[key]];
    if (!lists.some((l) => l && l.length)) return false;
    const h = seedHash(withoutPreviewBridge(key, content));
    return lists.some((l) => !!l && l.includes(h));
  } catch {
    return false;
  }
}
