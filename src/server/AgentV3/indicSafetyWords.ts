// QUEUE Q-321: THE SAFETY TRIAGE IN EVERY INDIAN SCRIPT, NOT ONLY DEVANAGARI.
//
// Q-102 taught `illegalContentRules.ts` Devanagari, and the same day measured the next gap: a request
// in Bengali, Tamil, Telugu, Gujarati, Gurmukhi, Kannada, Malayalam, Odia or Urdu was read by nobody.
// "পর্ন সাইট বানাও" was allowed while "porn site banao" was refused.
//
// 🔒 THE SAME PAIRING AND THE SAME PRECISION AS ENGLISH AND HINDI. Every list below mirrors its
// English twin field for field — a subject, a context, an illicit purpose, a stand-down — so a word
// here can never fire alone. The words are the ordinary ones: the loanwords people actually type
// (পর্ন, ভিডিও, অ্যাপ) and the plain standard word (অশ্লীল, ஆபாச, فحش). No slang dictionary, for the
// reason the rules file gives: a list of offender vocabulary in a source file is a lookup table.
//
// 🔒 PRECISION DECISIONS, each one a real collision found while writing the list:
//   - "app" carries an END in every script: Odia ଆପ starts ଆପଣ ("you"), and every script's "app"
//     starts its word for "apple". "Application" is listed on its own.
//   - "meth" carries an END: Bengali মেথি is fenugreek, Tamil மெத்தை and Malayalam മെത്ത a mattress.
//   - Telugu పిల్ల and Malayalam കുട്ടി also mean "girl" in speech, so the CHILD rule uses their plural
//     and formal forms (పిల్లల, కുട്ടികള); a sexual request about an adult is still refused by the
//     adult rule, it is simply not recorded as a child-abuse signal.
//   - Gurmukhi ਨੰਗੇ, like Hindi नंगे, is absent: "ਨੰਗੇ ਪੈਰ" is barefoot.
//
// ⚠️ How the text is matched (see `indicAlternatives`): words are NFC-normalised with zero-width
// characters removed, the same form `normalizeScanText` gives the input; a Malayalam chillu matches
// both of its spellings; an Urdu ی / ک / ہ also matches its Arabic-keyboard twin.
//
// ⚠️ Written without a native reader of every script, and so held to the strict side: a list that
// misses a word costs one model refusal (today's behaviour), a list that catches an innocent word
// costs a user. Additions belong here, in the same shape, with a test.

