import type { Express } from 'express';
import { rateLimiter } from '../lib/authMiddleware';
import { requireAccountForCostlyAi } from '../lib/costlyAiAccess';
import { voiceAiConfig, readVoiceInput, voicePrice, voiceCharacters, synthesizeVoice, VoiceAiError } from '../lib/voiceAi';
import { reserveVoice, finishVoice } from '../lib/voiceAiStore';
import { triagePrompt, blockMessage } from '../lib/promptSafety';
import { freeModuleInferenceScope, runWithInferenceScope } from '../AI/inferencePolicy';
import { assertAiAvailable } from '../lib/aiMaintenance';
import { audit } from '../lib/audit';
import { freeProgramPaused } from '../lib/freeProgram';
import { setFreeProgramPausedHint } from '../lib/freeProgramHint';

const messages: Record<string, string> = {
  unavailable: 'Voice AI is not available yet. Please try again later.',
  invalid: 'Check the text, language and voice, then try again.',
  price_changed: 'The price changed. Refresh Voice AI and review the new price before generating.',
  provider_failed: 'Voice generation could not finish. No automatic retry was made.',
  duplicate: 'This request was already received. It will not be generated or charged again.',
  insufficient: 'Your wallet does not cover this voice generation. Please add credits.',
  storage: 'Voice AI payment processing is unavailable. Please try again later.',
  busy: 'Voice AI is busy. Please wait before trying again.',
  cancelled: 'Voice generation was cancelled.',
};
export function registerVoiceAiRoutes(app: Express): void {
  app.get('/api/voice-ai/config', (_req, res) => {
    res.setHeader('Cache-Control', 'private, no-store');
    res.json(voiceAiConfig());
  });
  app.post('/api/voice-ai/generate', freeModuleInferenceScope,
    rateLimiter({ name: 'voice-ai', authed: 30, anon: 0, anonGlobalPerHour: 0, noun: 'voice generations' }), async (req, res) => {
    res.setHeader('Cache-Control', 'private, no-store');
    let hold: Awaited<ReturnType<typeof reserveVoice>> | undefined;
    const controller = new AbortController();
    const disconnected = () => { if (!res.writableFinished) controller.abort(); };
    res.on('close', disconnected);
    try {
      const account = await requireAccountForCostlyAi(req, 'voice generation');
      if (!account.ok) { res.status(account.status).json(account.body); return; }
      const input = readVoiceInput(req.body);
      const triage = triagePrompt(input.text);
      if (triage.verdict === 'block') { res.status(422).json({ error: blockMessage(triage.contentClass, input.text, triage.ruleId), code: 'blocked' }); return; }
      await assertAiAvailable();
      const config = voiceAiConfig();
      if (!config.available || config.pricePer1000CharactersInr === null) throw new VoiceAiError('unavailable');
      const fee = voicePrice(input.text, config.pricePer1000CharactersInr);
      if (input.acceptedPriceInr !== fee) throw new VoiceAiError('price_changed', 409);
      if (controller.signal.aborted) throw new VoiceAiError('cancelled', 499);
      // Cold instances must read the actual gift policy before the synchronous wallet debit.
      // A failed refresh can return PAUSED without changing the store's last-known hint.
      setFreeProgramPausedHint(await freeProgramPaused());
      if (controller.signal.aborted) throw new VoiceAiError('cancelled', 499);
      hold = await reserveVoice(account.uid, input.requestId, fee);
      if (controller.signal.aborted) throw new VoiceAiError('cancelled', 499);
      // A delayed database admission must not dispatch against an already expired hold.
      if (Date.now() >= hold.expiresAt) throw new VoiceAiError('unavailable');
      const audio = await runWithInferenceScope('paid-voice', () => synthesizeVoice(input, controller.signal));
      if (controller.signal.aborted) throw new VoiceAiError('cancelled', 499);
      // Settle only after the HTTP response finishes. A dropped connection or process crash
      // leaves a refundable hold; never charge merely because the provider generated bytes.
      // HTTP finish proves server delivery, not that the device saved or played the audio.
      const sent = await new Promise<boolean>((resolve, reject) => {
        const clean = () => { clearTimeout(flushDeadline); res.removeListener('finish', finished); res.removeListener('close', closed); };
        const flushDeadline = setTimeout(() => { clean(); res.destroy(); resolve(false); }, 120_000);
        flushDeadline.unref?.();
        const finished = () => { clean(); resolve(true); };
        const closed = () => { clean(); resolve(res.writableFinished); };
        res.once('finish', finished); res.once('close', closed);
        try { res.json({ audio, mimeType: 'audio/wav', chargedInr: fee, characters: voiceCharacters(input.text) }); }
        catch (error) { clean(); reject(error); }
      });
      const settled = await finishVoice(hold, sent);
      hold = undefined;
      if (settled) {
        audit('VOICE_AI_GENERATED', { uid: account.uid, requestId: input.requestId, characters: voiceCharacters(input.text), chargedInr: fee });
      }
    } catch (error) {
      let refundPending = false;
      if (hold) {
        try { await finishVoice(hold, false); } catch { refundPending = true; audit('VOICE_AI_REFUND_PENDING', { uid: hold.uid, operationId: hold.id }, 'error'); }
      }
      const known = error instanceof VoiceAiError ? error : new VoiceAiError('unavailable');
      if (!res.destroyed && !res.headersSent) res.status(known.status).json({ code: known.code,
        error: refundPending ? 'Voice generation failed. Your wallet refund is pending recovery; please do not repeat this request.' : messages[known.code] });
    } finally { res.removeListener('close', disconnected); }
  });
}
