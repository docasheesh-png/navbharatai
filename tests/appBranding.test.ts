import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { brandingNote, brandingSeed, brandingTextFiles, decideLogo } from '../src/server/lib/appBranding';
import { assembleMobileProject } from '../src/server/lib/mobileProjectAssembler';
import { generateShipKit } from '../src/server/lib/mobileShipKit';
import { chooseMark } from '../src/lib/brandMark';
import { planAppDefaults } from '../src/server/AgentV3/appDefaults';

const PNG = 'data:image/png;base64,iVBORw0KGgo=';
const files = { 'package.json': '{"name":"x","scripts":{"build":"vite build"}}', 'index.html': '<html></html>', 'src/main.tsx': 'x' };

describe('which logo does the app have?', () => {
  it('the owner\'s own logo wins', () => {
    expect(decideLogo({ iconDataUrl: PNG })).toEqual({ declared: 'user', dataUrl: PNG });
  });
  it('no logo → "none": the app then gets its own mark. NOTHING is generated by AI, bought, or fetched', () => {
    expect(decideLogo({})).toEqual({ declared: 'none' });
    expect(decideLogo({ iconDataUrl: '' })).toEqual({ declared: 'none' });
  });
  it('something that is not an image data URL is not a logo', () => {
    expect(decideLogo({ iconDataUrl: 'not-an-image' }).declared).toBe('none');
    expect(decideLogo({ iconDataUrl: 'data:text/html;base64,PGh0bWw+' }).declared).toBe('none');
  });
  it('source guard: no AI image generation anywhere in the branding path (admin 2026-10-21: "AI se logo nahi banwana")', () => {
    for (const f of ['src/server/lib/appBranding.ts', 'src/server/routes/mobileSetup.ts', 'src/server/lib/mobileProjectAssembler.ts']) {
      const src = readFileSync(f, 'utf8').replace(/\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '');
      expect(src, f).not.toMatch(/imageProHost|fetchImageProHostImage|generateAiLogo|serverAiLogoGenerator|aiLogoPrompt|MOBILE_AI_LOGO|IMAGE_PRO/);
    }
  });
});

describe('the project always carries the branding step and the drawn mark', () => {
  const asm = (o: Record<string, unknown>, name = 'Chai Shop', id = 'com.shop.chai') => assembleMobileProject(files, [], { appName: name, appId: id, ...o } as never);
  it('with a user logo: script + branding.json + the exact icon file + the mark (kept as the fallback)', () => {
    const p = asm({ iconDataUrl: PNG });
    expect(p.files['scripts/nbai-branding.mjs']).toContain('NavBharatAI app branding');
    expect(JSON.parse(p.files['resources/branding.json'])).toMatchObject({ declared: 'user', iconFile: 'resources/icon.png', appId: 'com.shop.chai', seed: brandingSeed('com.shop.chai', 'Chai Shop'), mark: 'lucide:coffee' });
    expect(p.binaryFiles['resources/icon.png']).toBeTruthy();
    expect(p.files['resources/brand-mark.svg']).toContain('data-nbai-mark="lucide:coffee"');
    expect(p.files['resources/brand-mark-fg.svg']).not.toContain('linearGradient');
  });
  it('with NO logo the step is still there and says "none" — the app gets its own mark, never Capacitor\'s default icon', () => {
    const p = asm({});
    expect(JSON.parse(p.files['resources/branding.json'])).toMatchObject({ declared: 'none', iconFile: '', mark: 'lucide:coffee' });
    expect(p.binaryFiles['resources/icon.png']).toBeUndefined();
    expect(p.notes.join(' ')).toMatch(/its own mark — a symbol that fits its name/);
    expect(p.notes.join(' ')).not.toMatch(/default icon/i);
  });
  it('a name with no fitting symbol: the note names the LETTER', () => {
    expect(asm({}, 'Pixelyt').notes.join(' ')).toMatch(/the letter P/);
    expect(JSON.parse(asm({}, 'Pixelyt').files['resources/branding.json']).mark).toBe('letter:P');
  });
  it('an unreadable logo is reported as "none" with its own note, not shipped', () => {
    const p = asm({ iconDataUrl: 'data:image/png;base64,@@@' });
    expect(JSON.parse(p.files['resources/branding.json']).declared).toBe('none');
  });
  it('two different apps get two different marks and colours; the drawn mark equals the web install icon\'s', () => {
    const a = asm({}, 'Chai Shop', 'com.a'), b = asm({}, 'Pixelyt', 'com.b');
    expect(a.files['resources/brand-mark.svg']).not.toBe(b.files['resources/brand-mark.svg']);
    // the SAME function drew both, so the web icon and the native icon are one mark
    expect(chooseMark('Chai Shop')).toEqual(chooseMark('Chai Shop'));
  });
  it('brandingNote tells the owner which icon they got', () => {
    expect(brandingNote({ declared: 'user' }, 'lucide:coffee')).toMatch(/Your logo/);
    expect(brandingNote({ declared: 'none' }, 'letter:P')).toMatch(/the letter P/);
    expect(brandingNote({ declared: 'none' }, 'lucide:coffee')).toMatch(/symbol that fits its name/);
    expect(Object.keys(brandingTextFiles({ appName: 'A', appId: 'b', decision: { declared: 'none' } })).sort()).toEqual([
      'resources/brand-mark-fg.svg', 'resources/brand-mark.svg', 'resources/branding.json', 'scripts/nbai-branding.mjs']);
  });
});

describe('every build lane runs the branding steps in the right order', () => {
  const kit = generateShipKit({ appName: 'Chai Shop', appId: 'com.shop.chai', ios: true } as never);
  const wf = Object.entries(kit.files).filter(([p]) => p.startsWith('.github/workflows/'));
  const text = (name: RegExp) => wf.filter(([p]) => name.test(p)).map(([, c]) => c).join('\n');
  it('every lane prepares the logo and writes the web install icons BEFORE the web build', () => {
    for (const [p, c] of wf) {
      expect(c, p).toContain('nbai-branding.mjs prepare');
      expect(c, p).toContain('nbai-branding.mjs pwa-apply');
      expect(c.indexOf('nbai-branding.mjs pwa-apply'), p).toBeLessThan(c.indexOf('name: Build the web app'));
      expect(c, p).toContain('@capacitor/assets sharp');
    }
  });
  it('Android APK and AAB: snapshot → ensure, and the build stops if the icon cannot be verified', () => {
    for (const body of [text(/apk/i), text(/aab|android-app|android\.yml/i)].filter(Boolean)) {
      expect(body.indexOf('nbai-branding.mjs prepare')).toBeLessThan(body.indexOf('snapshot android'));
      expect(body.indexOf('snapshot android')).toBeLessThan(body.indexOf('ensure android'));
      expect(body).toMatch(/if ! node scripts\/nbai-branding\.mjs ensure android; then[\s\S]{0,500}exit 1/);
    }
  });
  it('iOS: the same script with the same source', () => {
    const ios = text(/ios/i);
    expect(ios).toContain('nbai-branding.mjs snapshot ios'); expect(ios).toContain('nbai-branding.mjs ensure ios');
    expect(ios.indexOf('ensure ios')).toBeLessThan(ios.indexOf('fastlane'));
  });
  it('the web build checks the PWA install icons in all three lanes', () => {
    for (const [, c] of wf) expect(c).toContain('nbai-branding.mjs verify pwa');
  });
  it('the old "warn and ship the default icon" path is gone', () => {
    for (const [, c] of wf) {
      expect(c).not.toMatch(/could not generate the full icon set/);
      expect(c).not.toMatch(/capacitor\/assets generate --android --iconBackgroundColor '#ffffff' --iconBackgroundColorDark '#111111' \|\|/);
    }
  });
});

describe('the ship route decides the logo', () => {
  const route = readFileSync('src/server/routes/mobileSetup.ts', 'utf8');
  it('source guard: decideLogo runs before the project is assembled and its answer goes in', () => {
    expect(route.indexOf('decideLogo(')).toBeGreaterThan(0);
    expect(route.indexOf('decideLogo(')).toBeLessThan(route.indexOf('assembleMobileProject('));
    expect(route).toContain('branding: logo');
  });
});

describe('the web app\'s own install icon is the same mark', () => {
  it('source guard: appDefaults draws its icon with markSvg(chooseMark(name)) — no monogram, no fixed colour', () => {
    const src = readFileSync('src/server/AgentV3/appDefaults.ts', 'utf8').replace(/\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '');
    expect(src).toContain('markSvg(chooseMark(appName)');
    expect(src).not.toMatch(/<text|#0f172a"\/>/);
  });
});

describe('a framework\'s default favicon never survives in a generated web app', () => {
  const page = (link: string) => `<!doctype html><html><head><meta charset="UTF-8">${link}<title>Chai Shop</title></head><body><div id="root"></div></body></html>`;
  it.each(['/vite.svg', '/react.svg', '/favicon.ico', 'capacitor.png'])('%s is replaced with the app\'s own icon', (href) => {
    const r = planAppDefaults(page(`<link rel="icon" type="image/svg+xml" href="${href}" />`), 'Chai Shop');
    expect(r.indexHtml).toContain('href="/icon.svg"');
    expect(r.indexHtml).not.toContain(href);
    expect(r.added).toContain('icon link (replaced a framework default)');
  });
  it('an app\'s OWN icon link is left alone', () => {
    const r = planAppDefaults(page('<link rel="icon" href="/my-logo.png" />'), 'Chai Shop');
    expect(r.indexHtml).toContain('href="/my-logo.png"'); expect(r.indexHtml).not.toContain('href="/icon.svg"');
  });
  it('a page with no icon link gets the app\'s mark', () => {
    expect(planAppDefaults(page(''), 'Chai Shop').indexHtml).toContain('href="/icon.svg"');
  });
});
