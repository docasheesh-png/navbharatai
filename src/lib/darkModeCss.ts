// The dark-mode stylesheet the Dark Mode Generator writes into a USER'S app. PURE — no React, no I/O.
//
// 🔒 EVERY MAPPING DOES WHAT ITS TABLE SAYS (2026-10-11, Q-789). The "Color Mappings" table (Mapped Dark + an
// Override picker per colour) was shown for every strategy, but only "Manual Override" read it: CSS Variables
// (the recommended one), Class Toggle and color-scheme listed the mappings as CSS comments, so changing an
// override changed nothing. And Manual set `color` AND `background-color` of every matching element to the SAME
// value, painting text invisible on its own background. Now:
//   • a colour is swapped only on the property it was found on (`propertyForUsage`);
//   • a colour the user OVERRODE gets a real rule in every strategy, inside that strategy's dark scope;
//   • without overrides, the three non-manual strategies emit exactly what they emitted before.
// Locked by `tests/aDarkModeMappingDoesWhatItsTableSays.test.ts`.

export interface ColorMapping {
  original: string;
  dark: string;
  /** Where the colour was found: 'Background' | 'Text' | 'Neutral' | 'Accent'. */
  usage: string;
  override?: string;
}

export type DarkStrategy = 'css-vars' | 'class-toggle' | 'color-scheme' | 'manual';

export interface DarkTheme {
  bg: string;
  bgSecondary: string;
  text: string;
  textSecondary: string;
  accent: string;
  border: string;
}

/**
 * The ONE property a detected colour is swapped on, by where it was found. Background colours stay backgrounds
 * and text colours stay text, so a swap can never paint text the colour of its own background. Neutral greys
 * that were neither a background nor a text colour are, in practice, borders and dividers.
 */
export function propertyForUsage(usage: string): 'background-color' | 'color' | 'border-color' {
  if (usage === 'Background') return 'background-color';
  if (usage === 'Neutral') return 'border-color';
  return 'color';
}

/** One swap rule per mapping: elements whose inline style uses the colour get its dark value on ONE property. */
function swapRule(m: ColorMapping, indent: string, scope: string): string {
  return `${indent}/* ${m.usage}: ${m.original} */\n${indent}${scope}[style*="${m.original}"] { ${propertyForUsage(m.usage)}: ${m.override ?? m.dark} !important; }`;
}

/** The user's explicit overrides, as rules — or nothing, so a strategy without overrides is unchanged. */
function overrideRules(mappings: ColorMapping[], indent: string, scope = ''): string {
  const set = mappings.filter((m) => m.override);
  return set.length ? `\n${set.map((m) => swapRule(m, indent, scope)).join('\n')}` : '';
}

export function buildDarkCSS(mappings: ColorMapping[], strategy: DarkStrategy, theme: DarkTheme): string {
  const vars = `  --bg-primary: ${theme.bg};
  --bg-secondary: ${theme.bgSecondary};
  --text-primary: ${theme.text};
  --text-secondary: ${theme.textSecondary};
  --accent: ${theme.accent};
  --border: ${theme.border};`;

  if (strategy === 'css-vars') {
    return `/* Dark Mode — Auto-generated by NavBharatAI */
@media (prefers-color-scheme: dark) {
  :root {
${vars}
  }
  body {
    background: var(--bg-primary);
    color: var(--text-primary);
  }
  a { color: var(--accent); }
  input, textarea, select {
    background: var(--bg-secondary);
    color: var(--text-primary);
    border-color: var(--border);
  }
  button {
    background: var(--bg-secondary);
    color: var(--text-primary);
    border: 1px solid var(--border);
  }
${mappings.filter((m) => !m.override).map(m => `  /* ${m.usage}: ${m.original} */`).join('\n')}${overrideRules(mappings, '  ')}
}`;
  }

  if (strategy === 'class-toggle') {
    return `/* Dark Mode (class toggle) — Auto-generated by NavBharatAI */
html.dark {
  --bg-primary: ${theme.bg};
  --bg-secondary: ${theme.bgSecondary};
  --text-primary: ${theme.text};
  --text-secondary: ${theme.textSecondary};
  --accent: ${theme.accent};
  --border: ${theme.border};
}
html.dark body {
  background: var(--bg-primary);
  color: var(--text-primary);
}
html.dark a { color: var(--accent); }
html.dark input, html.dark textarea, html.dark select {
  background: var(--bg-secondary);
  color: var(--text-primary);
  border-color: var(--border);
}${overrideRules(mappings, '', 'html.dark ')}`;
  }

  if (strategy === 'color-scheme') {
    return `/* Dark Mode (color-scheme) — Auto-generated by NavBharatAI */
:root { color-scheme: light dark; }
@media (prefers-color-scheme: dark) {
  body { background: ${theme.bg}; color: ${theme.text}; }${overrideRules(mappings, '  ')}
}`;
  }

  // manual — every mapping is swapped, each on its own property
  return `/* Dark Mode (manual overrides) — Auto-generated by NavBharatAI */
@media (prefers-color-scheme: dark) {
${mappings.map((m) => swapRule(m, '  ', '')).join('\n')}
}`;
}
